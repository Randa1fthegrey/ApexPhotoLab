    private static byte[] create2BitTile(byte[] plane0, byte[] plane1) {
        byte[] tile = new byte[16];
        System.arraycopy(plane0, 0, tile, 0, 8);
        System.arraycopy(plane1, 0, tile, 8, 8);
        return tile;
    }

    public static byte[] getPcbTile(int tileIdx) {
        if (tileIdx >= 0 && tileIdx < 32 && PCB_TILES[tileIdx] != null) {
            return PCB_TILES[tileIdx];
        }
        return PCB_TILES[NES_Tile_Constants.TILE_BLANK];
    }
