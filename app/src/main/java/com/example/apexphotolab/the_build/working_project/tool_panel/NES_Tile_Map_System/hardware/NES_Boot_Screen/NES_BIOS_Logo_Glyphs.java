    private static byte[] create2BitTile(byte[] plane0, byte[] plane1) {
        byte[] tile = new byte[16];
        System.arraycopy(plane0, 0, tile, 0, 8);
        System.arraycopy(plane1, 0, tile, 8, 8);
        return tile;
    }

    public static byte[] getLogoTile(int tileIdx) {
        if (tileIdx >= 0x80 && tileIdx < 0x0A0 && LOGO_GLYPHS[tileIdx] != null) {
            return LOGO_GLYPHS[tileIdx];
        }
        return null;
    }
